"""Structured Pydantic schemas for specialist agents and LLM outputs."""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class DocumentExtractionResult(BaseModel):
    """Unified 1-call extraction schema for Document Specialist Agent."""
    doc_type: str = Field(
        description="Type of document (e.g. claim_form, itemized_bill, medical_record, other)"
    )
    confidence: float = Field(
        ge=0.0, le=1.0, description="OCR and extraction confidence score (0.0 to 1.0)"
    )
    claimant_name: Optional[str] = Field(
        default=None, description="Extracted patient or claimant name"
    )
    policy_number: Optional[str] = Field(
        default=None, description="Policy or member identification number"
    )
    date_of_service: Optional[str] = Field(
        default=None, description="Service or treatment date (YYYY-MM-DD)"
    )
    total_amount: Optional[float] = Field(
        default=None, description="Total billed or claimed dollar amount"
    )
    diagnosis: Optional[str] = Field(
        default=None, description="Clinical diagnosis or ICD/condition description"
    )
    procedure: Optional[str] = Field(
        default=None, description="Procedure or treatment performed"
    )
    extracted_fields: Dict[str, Any] = Field(
        default_factory=dict, description="Normalized key-value fields from document"
    )
    is_injection_flagged: bool = Field(
        default=False, description="Whether adversarial prompt injection was detected"
    )
    injection_rationale: Optional[str] = Field(
        default=None, description="Explanation if prompt injection detected"
    )
    validation_status: Literal["VALID", "INVALID", "LOW_CONFIDENCE", "SUSPECTED_INJECTION"] = Field(
        default="VALID", description="Validation status of the document"
    )


class CaseSummaryResult(BaseModel):
    """Structured synthesis result generated by Summary Specialist Agent."""
    case_id: str
    facts: str = Field(description="Clinical and service facts synthesized from documents")
    evidence: str = Field(description="Cited evidence and supporting documentation")
    missing_info: str = Field(description="Identified missing documentation or prior authorizations")
    risks: List[str] = Field(default_factory=list, description="Policy, financial, or clinical risks")
    policy_citations: List[str] = Field(
        default_factory=list, description="Citations to exact policy clauses"
    )
    next_action: Literal["APPROVE", "REJECT", "MANUAL_REVIEW", "REQUEST_DOCUMENTS"] = Field(
        description="Recommended disposition for human review"
    )


class RoutingResult(BaseModel):
    """Routing and assignment result generated by Routing Specialist Agent."""
    case_id: str
    assigned_adjuster_id: str
    assigned_approver_id: str
    approver_limit: float
    claim_amount: float
    rationale: str
    status: Literal["ASSIGNED", "ROUTED_FOR_APPROVAL", "FAILED"] = "ROUTED_FOR_APPROVAL"


class IntakeResult(BaseModel):
    """Intake triage result generated by Intake Specialist Agent."""
    case_id: str
    is_covered: bool
    coverage_reason: str
    is_duplicate: bool
    duplicate_case_id: Optional[str] = None
    duplicate_reason: Optional[str] = None
    recommendation: Literal["PROCEED", "REJECT_OUT_OF_POLICY", "FLAG_DUPLICATE"]


class SLACommsResult(BaseModel):
    """Communication and SLA dispatch result generated by SLA & Comms Agent."""
    case_id: str
    sla_scheduled: bool = False
    notification_sent: bool = False
    documents_requested: bool = False
    details: Dict[str, Any] = Field(default_factory=dict)


class Route(BaseModel):
    """Supervisor dynamic routing decision schema."""
    next: Literal[
        "intake_agent",
        "document_fanout",
        "summary_agent",
        "routing_agent",
        "sla_agent",
        "human_review",
        "await_documents",
        "manual_review",
        "finalize",
        "end",
    ] = Field(description="Next specialist agent node or destination in workflow")
    reason: str = Field(description="Operational rationale for selecting the next step")


